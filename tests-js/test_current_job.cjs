const fs=require('fs'),vm=require('vm'),assert=require('assert');
const s=fs.readFileSync('cloud_client.js','utf8');
const code=s.slice(s.indexOf('function currentJobOutcome'),s.indexOf("  $('review-confirm')"));
const ctx={};vm.createContext(ctx);vm.runInContext(code,ctx);
const entry={id:'old-recipe',recipe:{auto_review:{passed:true},art_status:'completed'}};
const jobs=[{id:'old',state:'completed',recipe_id:'old-recipe'},{id:'new',state:'failed',error:'download failed'}];
assert.equal(ctx.currentJobOutcome(jobs,[entry],'new').state,'failed');
assert.equal(ctx.currentJobOutcome(jobs,[entry],'missing').state,'missing');
jobs[1]={id:'new',state:'running'};
assert.equal(ctx.currentJobOutcome(jobs,[entry],'new').state,'running');
jobs[1]={id:'new',state:'completed',recipe_id:'new-recipe'};
assert.equal(ctx.currentJobOutcome(jobs,[entry],'new').state,'missing');
const current={id:'new-recipe',recipe:{auto_review:{passed:true},art_status:'completed'}};
assert.strictEqual(ctx.currentJobOutcome(jobs,[entry,current],'new').entry,current);
current.recipe.art_status='failed';
assert.equal(ctx.currentJobOutcome(jobs,[entry,current],'new').state,'incomplete');
current.recipe.art_status='completed';current.recipe.auto_review.passed=false;current.recipe.note_status='needs_confirmation';
assert.equal(ctx.currentJobOutcome(jobs,[entry,current],'new').state,'completed');
console.log('PASS: current failed/running/missing task cannot open historical recipes; only its complete recipe opens.');
